const fs = require('fs');
const path = require('path');

const EX_DIR = 'data/examples';
const KP_DIR = 'data/knowledge';

const upperKP = JSON.parse(fs.readFileSync(path.join(KP_DIR, 'g3_math_upper.json'), 'utf8'));
const lowerKP = JSON.parse(fs.readFileSync(path.join(KP_DIR, 'g3_math_lower.json'), 'utf8'));
const allKP = [...upperKP, ...lowerKP];

const kpById = {};
allKP.forEach(kp => { kpById[kp.id] = kp; });

function mcq(q, opts, correct, exp) {
  const labels = ['A', 'B', 'C', 'D'];
  return {
    question: '选择题：' + q + '（  ）\n' + opts.map((o, i) => labels[i] + '. ' + o).join('\n'),
    answer: '答案：' + labels[correct] + '\n解析：' + exp
  };
}

function fill(q, a, exp) {
  return { question: '填空题：' + q, answer: '答案：' + a + '\n解析：' + exp };
}

function judge(q, right, exp) {
  return { question: '判断题：' + q + '（  ）', answer: '答案：' + (right ? '正确' : '错误') + '\n解析：' + exp };
}

function solve(q, a, exp) {
  return { question: '解答题：' + q, answer: '答案：' + a + '\n解析：' + exp };
}

function makeExamples(id, arr) {
  return arr.map((ex, i) => ({
    id: id + '_ex' + String(i+1).padStart(2, '0'),
    knowledge_id: id,
    question: ex.question,
    answer: ex.answer
  }));
}

