function rand(min, max) {
  return Math.floor(Math.random() * (max - min + 1)) + min;
}

function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

function mcq(question, options, correctIdx, explanation) {
  const labels = ['A', 'B', 'C', 'D'];
  const qText = '选择题：' + question + '（  ）\n' +
    options.map((opt, i) => labels[i] + '. ' + opt).join('\n');
  const ans = '答案：' + labels[correctIdx] + '\n解析：' + explanation;
  return { question: qText, answer: ans };
}

function fill(q, a, exp) {
  return {
    question: '填空题：' + q,
    answer: '答案：' + a + '\n解析：' + exp
  };
}

function judge(q, isRight, exp) {
  return {
    question: '判断题：' + q + '（  ）',
    answer: '答案：' + (isRight ? '正确' : '错误') + '\n解析：' + exp
  };
}

function solve(q, a, exp) {
  return {
    question: '解答题：' + q,
    answer: '答案：' + a + '\n解析：' + exp
  };
}

