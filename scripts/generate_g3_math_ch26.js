const fs = require('fs');
const path = require('path');

const EX_DIR = 'data/examples';

// 辅助函数：生成选择题
function mcq(question, options, correctIndex, analysis) {
    const optionText = options.map((o, i) => `${['A','B','C','D'][i]}. ${o}`).join('\n');
    return {
        question: `选择题：${question}\n${optionText}`,
        answer: `答案：${['A','B','C','D'][correctIndex]}\n解析：${analysis}`
    };
}

// 辅助函数：生成填空题
function fill(question, answer, analysis) {
    return {
        question: `填空题：${question}`,
        answer: `答案：${answer}\n解析：${analysis}`
    };
}

// 辅助函数：生成判断题
function judge(question, answer, analysis) {
    const ans = answer ? '正确' : '错误';
    return {
        question: `判断题：${question}（  ）`,
        answer: `答案：${ans}\n解析：${analysis}`
    };
}

// 辅助函数：生成解答题
function solve(question, answer, analysis) {
    return {
        question: `解答题：${question}`,
        answer: `答案：${answer}\n解析：${analysis}`
    };
}

// 辅助函数：组织例题数组
function makeExamples(knowledgeId, examples) {
    return examples.map((ex, i) => ({
        id: `${knowledgeId}_ex${String(i+1).padStart(2, '0')}`,
        knowledge_id: knowledgeId,
        ...ex
    }));
}

// ========== g3_math_036: 反比例函数的概念 ==========
function gen_036() {
    const exs = [];
    
    exs.push(mcq('下列函数是反比例函数的是',
        ['y = 2x', 'y = x/3', 'y = 1/x', 'y = x²'],
        2,
        '反比例函数的形式为y = k/x（k≠0）。y = 1/x符合，其中k = 1。其他选项：y=2x是一次函数，y=x/3是一次函数，y=x²是二次函数。'));
    
    exs.push(fill('反比例函数的一般形式是y = k/x，其中k为常数且k ≠ ______，自变量x的取值范围是______。',
        '0，x ≠ 0',
        '反比例函数定义：y = k/x（k≠0）。自变量x在分母，所以x≠0；函数值y也≠0。'));
    
    exs.push(mcq('反比例函数y = -2/x的比例系数k是',
        ['2', '-2', '1', '-1'],
        1,
        '反比例函数y = k/x中的k叫做比例系数。在y = -2/x中，k = -2。'));
    
    exs.push(fill('已知函数y = -3/x，当x = 2时，y = ______；当y = 6时，x = ______。',
        '-1.5，-0.5',
        '代入计算：x=2时，y=-3/2=-1.5；y=6时，-3/x=6，解得x=-3/6=-0.5。'));
    
    exs.push(judge('反比例函数y = k/x中，自变量x的次数是-1。',
        true,
        '反比例函数y = k/x可以写成y = kx⁻¹，自变量x的次数是-1。这是判断反比例函数的一个标准。'));
    
    exs.push(mcq('下列关系式中，y与x成反比例的是',
        ['y = 2x + 1', 'xy = 6', 'y = 3 - x', 'y/x = 2'],
        1,
        'y与x成反比例的条件是xy = k（k≠0）。xy = 6符合，其中k = 6，所以y = 6/x是反比例函数。'));
    
    exs.push(fill('若函数y = (m-2)/x是反比例函数，则m的取值范围是______。',
        'm ≠ 2',
        '反比例函数y = k/x要求k≠0。这里k = m-2，所以m-2≠0，即m≠2。'));
    
    exs.push(mcq('路程s一定时，速度v与时间t的关系是',
        ['v = st', 'v = s/t', 'v = t/s', 'v = s + t'],
        1,
        '路程s = vt，当s一定时，v = s/t，这是反比例函数关系。速度与时间成反比。'));
    
    exs.push(fill('等价形式判断：反比例函数可以表示为y = k/x，也可以表示为______（k≠0）或______（k≠0）。',
        'y = kx⁻¹，xy = k',
        '反比例函数的三种等价形式：y = k/x，y = kx⁻¹，xy = k。这三种形式本质相同。'));
    
    exs.push(solve('已知反比例函数y = k/x的图象经过点P(2, -3)。(1)求k的值；(2)判断点Q(-1, 6)是否在此函数图象上。',
        '(1)k = -6；(2)点Q在图象上',
        '(1)点P(2, -3)在函数y = k/x上，代入得：-3 = k/2，所以k = -6。\n(2)函数为y = -6/x。检验点Q(-1, 6)：x=-1时，y=-6/(-1)=6，与Q点坐标吻合，所以点Q在图象上。\n也可用xy = k检验：(-1)×6 = -6 = k ✓'));
    
    return makeExamples('g3_math_036', exs);
}

// ========== g3_math_037: 反比例函数的图象和性质 ==========
