function rand(min, max) {
  return Math.floor(Math.random() * (max - min + 1)) + min;
}

function randInts(min, max, n) {
  const result = [];
  while (result.length < n) {
    const r = rand(min, max);
    if (!result.includes(r)) result.push(r);
  }
  return result;
}

function mcq(q, opts, correct, exp) {
  const labels = ['A', 'B', 'C', 'D'];
  return {
    question: '选择题：' + q + '（  ）\n' + opts.map((o, i) => labels[i] + '. ' + o).join('\n'),
    answer: '答案：' + labels[correct] + '\n解析：' + exp
  };
}

function fill(q, a, exp) {
  return {
    question: '填空题：' + q,
    answer: '答案：' + a + '\n解析：' + exp
  };
}

function judge(q, right, exp) {
  return {
    question: '判断题：' + q + '（  ）',
    answer: '答案：' + (right ? '正确' : '错误') + '\n解析：' + exp
  };
}

function solve(q, a, exp) {
  return {
    question: '解答题：' + q,
    answer: '答案：' + a + '\n解析：' + exp
  };
}

function makeExamples(id, arr) {
  return arr.map((ex, i) => ({
    id: id + '_ex' + String(i+1).padStart(2, '0'),
    knowledge_id: id,
    question: ex.question,
    answer: ex.answer
  }));
}

