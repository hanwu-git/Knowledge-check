function generateSubject(subject, knowledgeFiles, semesterMap) {
  console.log(`\n=== 生成${subject}科目例题 ===`);
  let totalFiles = 0;
  let totalQuestions = 0;

  for (const [semester, files] of Object.entries(knowledgeFiles)) {
    console.log(`\n${semester === 'u' ? '上册' : '下册'}：`);
    
    for (let i = 0; i < files.length; i++) {
      const knowledge = files[i];
      let examples;
      
      if (subject === 'math') {
        examples = generateMathExamples(knowledge, i, semester);
      } else if (subject === 'physics') {
        examples = generatePhysicsExamples(knowledge, i, semester);
      } else if (subject === 'biology') {
        examples = generateBiologyExamples(knowledge, i, semester);
      } else {
        continue;
      }

      const fileName = `${knowledge.id}_010.json`;
      const filePath = path.join(EXAMPLES_DIR, fileName);
      
      fs.writeFileSync(filePath, JSON.stringify(examples, null, 2), 'utf-8');
      
      totalFiles++;
      totalQuestions += examples.length;
      
      if (i < 3) {
        console.log(`  生成 ${fileName}（${knowledge.name}）- ${examples.length}题`);
      }
    }
    console.log(`  上册/下册合计 ${files.length} 个知识点`);
  }

  console.log(`\n${subject}科目完成：${totalFiles}个文件，${totalQuestions}道题`);
  return { totalFiles, totalQuestions };
}

function loadKnowledge(filename) {
  const filePath = path.join(KNOWLEDGE_DIR, filename);
  return JSON.parse(fs.readFileSync(filePath, 'utf-8'));
}

