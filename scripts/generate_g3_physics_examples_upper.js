function mcq(q, opts, ci, a) {
    const t = opts.map((o, i) => `${['A','B','C','D'][i]}. ${o}`).join('\n');
    return { question: `选择题：${q}\n${t}`, answer: `答案：${['A','B','C','D'][ci]}\n解析：${a}` };
}
function fill(q, a, exp) { return { question: `填空题：${q}`, answer: `答案：${a}\n解析：${exp}` }; }
function judge(q, v, exp) { return { question: `判断题：${q}（  ）`, answer: `答案：${v?'正确':'错误'}\n解析：${exp}` }; }
function solve(q, a, exp) { return { question: `解答题：${q}`, answer: `答案：${a}\n解析：${exp}` }; }
function mk(id, arr) { return arr.map((e, i) => ({ id: `g3_physics_${String(id).padStart(3,'0')}_ex${String(i+1).padStart(2,'0')}`, knowledge_id: `g3_physics_${String(id).padStart(3,'0')}`, ...e })); }

